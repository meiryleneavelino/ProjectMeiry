def build(skip_build):
    if skip_build:
        return
    step("Building horus-ledger (chaincode, SAST agent, gateway) and the organization SAST images")
    run([DOCKER, "build", "-t", LEDGER_IMAGE, str(ROOT / "ledger")])
    build_images()


def load_images():
    step("Loading images into kind (nothing is pulled inside the cluster)")
    images = [*FABRIC_IMAGES, LEDGER_IMAGE, *(item["image"] for item in orgs().values())]
    node = f"{CLUSTER}-control-plane"
    platform = "linux/" + run([DOCKER, "info", "-f", "{{.Architecture}}"], capture=True).stdout.decode().strip() \
        .replace("aarch64", "arm64").replace("x86_64", "amd64")
    for image in images:
        reference = image if "/" in image.split(":")[0] else f"library/{image}"
        if image in FABRIC_IMAGES and run([DOCKER, "exec", node, "crictl", "inspecti", f"docker.io/{reference}"],
                                          capture=True, check=False).returncode == 0:
            print(f"   {image} already on the node")
            continue
        if tools("kind", "load", "docker-image", image, "--name", CLUSTER, capture=True, check=False).returncode:
            # Multi-platform images pulled by Docker Desktop only contain the local
            # platform's layers; export just that platform and import it on the node.
            exported = run([DOCKER, "save", "--platform", platform, image], capture=True).stdout
            run([DOCKER, "exec", "-i", node, "ctr", "--namespace=k8s.io", "images", "import",
                 "--snapshotter=overlayfs", "-"], input_data=exported, capture=True)
        print(f"   loaded {image}")


def secret_exists(namespace, name):
    return kubectl("get", "secret", name, "-n", namespace, capture=True, check=False).returncode == 0


def bootstrap_secrets():
    step("Creating each organization's CA bootstrap secret inside its own namespace")
    for name, item in orgs().items():
        namespace = item["namespace"]
        if secret_exists(namespace, "ledger-ca-bootstrap"):
            print(f"   {name}: already present")
            continue
        kubectl("create", "secret", "generic", "ledger-ca-bootstrap", "-n", namespace,
                "--from-file=password=/dev/stdin", input_data=secrets.token_hex(24).encode(), capture=True)
        print(f"   {name}: created")
    token_file = LOCAL / "gateway-token"
    if not token_file.exists():
        write_private(token_file, secrets.token_urlsafe(32))
    namespace = orgs()[researcher_org()]["namespace"]
    tools("sh", "-c", f"kubectl --context {CONTEXT} create secret generic ledger-gateway-token -n {namespace} "
          "--from-file=token=/dev/stdin --dry-run=client -o yaml | "
          f"kubectl --context {CONTEXT} apply -f - >/dev/null", input_data=token_file.read_bytes())


def wait_nodes():
    step("Waiting for CAs, enrollment Jobs, orderers, peers and admin consoles")
    for name, item in orgs().items():
        namespace = item["namespace"]
        kubectl("wait", "--for=condition=complete", "job/ledger-enroll", "-n", namespace, "--timeout=300s")
        for deployment in ("orderer0", "peer0", "ledger-admin"):
            kubectl("rollout", "status", f"deployment/{deployment}", "-n", namespace, "--timeout=300s")
        print(f"   {name}: identities enrolled, orderer and peer ready")


def public_material():
    """Collect every organization's PUBLIC folder (no private keys inside)."""
    bundles = {}
    for name in orgs():
        data = admin(name, "tar -C /crypto/public -cf - .").stdout
        with tarfile.open(fileobj=io.BytesIO(data)) as archive:
            names = archive.getnames()
            if any("keystore" in member or member.endswith(".key") for member in names):
                raise RuntimeError(f"{name} public bundle unexpectedly contains key material")
        bundles[name] = data
        write_private(LOCAL / "public" / f"{name}.tar", data)
    return bundles


def stage_public(target, bundles):
    """Place all organizations' public MSPs into one admin console's /work/orgs."""
    for name, data in bundles.items():
        admin(target, f"rm -rf /work/orgs/{name} && mkdir -p /work/orgs/{name} && tar -C /work/orgs/{name} -xf -",
              input_data=data)


