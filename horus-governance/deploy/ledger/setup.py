def step(message):
    print(f"\n==> {message}", flush=True)


def run(arguments, input_data=None, capture=False, check=True):
    result = subprocess.run(arguments, input=input_data, capture_output=capture, check=False)
    if check and result.returncode:
        detail = (result.stderr or b"").decode(errors="replace")[-2000:] if capture else ""
        raise RuntimeError(f"command failed ({result.returncode}): {' '.join(arguments[:6])}...\n{detail}")
    return result


def tools(*arguments, input_data=None, capture=False, check=True):
    return run([DOCKER, "exec", "-i", TOOLS, *arguments], input_data, capture, check)


def kubectl(*arguments, input_data=None, capture=False, check=True):
    return tools("kubectl", "--context", CONTEXT, *arguments, input_data=input_data, capture=capture, check=check)


def orgs():
    """organizations.json order: UVA, VU, TUDELFT."""
    return organizations()


def researcher_org():
    from app.settings import Settings
    return Settings.load().organization


def admin(organization, script, input_data=None, capture=True, check=True):
    """Run a shell script in the organization's admin console (its own admin key)."""
    namespace = orgs()[organization]["namespace"]
    result = kubectl("exec", "-i", "-n", namespace, "deploy/ledger-admin", "-c", "admin", "--",
                     "sh", "-c", script, input_data=input_data, capture=capture, check=check)
    return result


def admin_text(organization, script, check=True):
    result = admin(organization, script, check=check)
    return result.stdout.decode().strip(), result.returncode


# --------------------------------------------------------------------------- config

def image_id(image):
    return run([DOCKER, "image", "inspect", "-f", "{{.Id}}", image], capture=True).stdout.decode().strip()


def governance_config():
    rules_bytes = (ROOT / "sast" / "rules.yaml").read_bytes()
    policy = json.loads((ROOT / "config" / "policy.json").read_bytes())
    rules = {rule["id"]: {"severity": rule["metadata"]["horus_severity"], "message": rule["message"]}
             for rule in json.loads(rules_bytes)["rules"]}
    return {
        "version": 1, "channel": CHANNEL,
        "organizations": {name: item["msp"] for name, item in orgs().items()},
        "rules_hash": hashlib.sha256(rules_bytes).hexdigest(),
        "policy_hash": content_hash(canonical_json(policy)),
        "semgrep_version": SEMGREP_VERSION,
        "analyzer_images": {name: image_id(item["image"]) for name, item in orgs().items()},
        "rules": rules,
        "policy": {"deductions": policy["deductions"], "minimum_score": policy["minimum_score"],
                   "maximum_high_findings": policy["maximum_high_findings"]},
        "reveal_timeout_seconds": REVEAL_TIMEOUT_SECONDS,
    }


def values(config, chaincode_ids=None, agents=False, gateway=False):
    researcher = researcher_org()
    return {
        "channel": CHANNEL, "chaincode": CHAINCODE,
        "organizations": [{"name": name, "namespace": item["namespace"], "msp": item["msp"],
                           "analyzerImage": item["image"], "researcher": name == researcher}
                          for name, item in orgs().items()],
        "governanceConfig": json.dumps(config, sort_keys=True, separators=(",", ":")),
        "chaincodeIds": chaincode_ids or {}, "agents": {"enabled": agents, "audit": True},
        "gateway": {"enabled": gateway}, "ledgerImageId": image_id(LEDGER_IMAGE),
    }


def write_private(path, content):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "wb") as target:
        target.write(content if isinstance(content, bytes) else content.encode())


def helm(release_values):
    """Copy the chart into the tools container (it does not mount this checkout) and apply it."""
    write_private(LOCAL / "values.json", json.dumps(release_values, indent=2))
    tools("rm", "-rf", REMOTE)
    tools("mkdir", "-p", REMOTE)
    run([DOCKER, "cp", str(CHART), f"{TOOLS}:{REMOTE}/chart"])
    run([DOCKER, "cp", str(LOCAL / "values.json"), f"{TOOLS}:{REMOTE}/values.json"])
    tools("helm", "upgrade", "--install", RELEASE, f"{REMOTE}/chart", "--kube-context", CONTEXT,
          "--namespace", RELEASE_NAMESPACE, "-f", f"{REMOTE}/values.json")
    tools("rm", "-f", f"{REMOTE}/values.json")


