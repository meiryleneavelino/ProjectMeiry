"""Bring up the Horus governance ledger (Hyperledger Fabric 2.5) in the kind cluster.

Each step acts as the operator of ONE organization inside that organization's
namespace. Between organizations only public material moves: CA certificates,
NodeOU configuration, orderer TLS certificates and the channel genesis block.
Private keys are generated by each organization's own CA Job and stay on that
organization's volume.

Usage (from horus-governance/):  python3 tools.py ledger setup|status|verify|forward|down
"""
